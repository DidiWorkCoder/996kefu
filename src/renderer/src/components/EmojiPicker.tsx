interface Props {
  disabled?: boolean;
  /** 选中一个表情（调用方负责插到输入框光标处） */
  onPick: (emoji: string) => void;
}

/** 表情选择器：点「表情」弹出，选中后不自动关闭，可以连着选多个 */
export default function EmojiPicker({ disabled, onPick }: Props) {
  const [open, setOpen] = useState(false);
  const [group, setGroup] = useState(GROUPS[0].key);
  const current = GROUPS.find((g) => g.key === group) || GROUPS[0];

  const content = (
    <div className="emoji-panel">
      <div className="emoji-tabs">
        {GROUPS.map((g) => (
          <span
            key={g.key}
            className={`emoji-tab ${g.key === current.key ? 'active' : ''}`}
            onClick={() => setGroup(g.key)}
          >
            {g.label}
          </span>
        ))}
      </div>
      <div className="emoji-grid">
        {current.emojis.map((e) => (
          <span key={e} className="emoji-item" onClick={() => onPick(e)}>
            {e}
          </span>
        ))}
      </div>
    </div>
  );

  return (
    <Popover open={open} onOpenChange={setOpen} trigger="click" placement="topLeft" arrow={false} content={content}>
      <Button icon={<SmileOutlined />} disabled={disabled}>
        表情
      </Button>
    </Popover>
  );
}
